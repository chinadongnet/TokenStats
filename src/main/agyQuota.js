// Antigravity (agy) live-quota integration.
//
// Current agy exposes quota through its built-in `/usage` JSON command; the
// main process refreshes it every 20s while this integration is enabled.
// The opt-in statusLine mirror remains a fallback, accepted only when fresh.
// Headless AGY sessions don't render statusLine, so mirror-only reads can freeze
// indefinitely. Never label an expired mirror or quota window as live.
//
// This is the ONE place that edits another tool's config, always user-initiated
// via the Settings toggle, reversible, and it never clobbers a statusLine the
// user set themselves.

import os from 'node:os'
import path from 'node:path'
import fs from 'node:fs'
import { agyLiveWindows, agyQuotaAgeMs, parseAgyQuota } from './core/agyLimits.js'

const home = os.homedir()

// agy's own settings file (holds the statusLine config).
const AGY_SETTINGS = path.join(home, '.gemini', 'antigravity-cli', 'settings.json')
// Our files live under TokenStats' config dir.
const TOKENSTATS_DIR = path.join(home, '.tokenstats')
const HOOK_PATH = path.join(TOKENSTATS_DIR, 'agyStatusHook.cjs')
export const AGY_MIRROR_PATH = path.join(TOKENSTATS_DIR, 'agy_status.json')
// Whatever `statusLine` agy had before we installed ours (including "absent",
// stored as null), so disabling restores it exactly instead of leaving behind
// our own empty-command stub.
const BACKUP_PATH = path.join(TOKENSTATS_DIR, 'agyStatusLineBackup.json')

// Forward-slash form for the path inside both the JS hook source and the
// command string.
const fwd = (p) => p.replace(/\\/g, '/')
// The exact statusLine command we install; used verbatim to detect "is ours".
// NOTE: agy executes `command` by splitting on spaces WITHOUT shell/quote
// handling (verified on Windows), so the path must NOT be quoted — quotes get
// passed to node literally and break it. This means a hook path containing a
// space wouldn't work; ~/.tokenstats sits under the home dir, so that only
// happens if the Windows username has a space (rare). Kept unquoted for the
// common case.
const OUR_COMMAND = `node ${fwd(HOOK_PATH)}`

// The hook script agy executes. Reads the piped session JSON from stdin,
// mirrors it to AGY_MIRROR_PATH, and prints a compact status line back so the
// user still gets a useful agy status bar (model · context% · gemini quota%).
// Dependency-free (only `fs`); runs under the system `node` agy invokes.
const HOOK_SRC = `// Auto-generated by TokenStats — mirrors agy's live session/quota JSON.
// Managed by the "Antigravity live quota" toggle in TokenStats Settings.
const fs = require('fs')
const MIRROR = ${JSON.stringify(fwd(AGY_MIRROR_PATH))}
let raw = ''
try { raw = fs.readFileSync(0, 'utf8') } catch (e) {}
try { if (raw && raw.trim()) fs.writeFileSync(MIRROR, raw) } catch (e) {}
try {
  const d = JSON.parse(raw)
  const parts = []
  if (d.model && d.model.display_name) parts.push(d.model.display_name)
  const cw = d.context_window
  if (cw && typeof cw.used_percentage === 'number') parts.push('ctx ' + Math.round(cw.used_percentage) + '%')
  if (d.quota) {
    const fr = Object.keys(d.quota)
      .filter((k) => /^gemini/i.test(k))
      .map((k) => d.quota[k] && d.quota[k].remaining_fraction)
      .filter((x) => typeof x === 'number')
    if (fr.length) parts.push('gemini ' + Math.round(Math.min.apply(null, fr) * 100) + '%')
  }
  process.stdout.write(parts.join('  |  ') || 'agy')
} catch (e) {
  process.stdout.write('agy')
}
`

function readAgySettings() {
  try {
    return JSON.parse(fs.readFileSync(AGY_SETTINGS, 'utf8'))
  } catch {
    return null
  }
}

function writeAgySettings(cfg) {
  fs.writeFileSync(AGY_SETTINGS, JSON.stringify(cfg, null, 2))
}

function writeHookFile() {
  fs.mkdirSync(TOKENSTATS_DIR, { recursive: true })
  fs.writeFileSync(HOOK_PATH, HOOK_SRC)
}

// Backup of agy's original statusLine: `{ had: bool, value: <original> }`.
// `had:false` means agy had no statusLine key at all, so restoring deletes it.
function saveStatusLineBackup(cfg) {
  try {
    fs.mkdirSync(TOKENSTATS_DIR, { recursive: true })
    const had = Object.prototype.hasOwnProperty.call(cfg, 'statusLine')
    fs.writeFileSync(BACKUP_PATH, JSON.stringify({ had, value: had ? cfg.statusLine : null }, null, 2))
  } catch {
    // best-effort — a missing backup just means disable falls back to deleting
  }
}

function readStatusLineBackup() {
  try {
    const b = JSON.parse(fs.readFileSync(BACKUP_PATH, 'utf8'))
    if (b && typeof b === 'object' && 'had' in b) return b
  } catch {
    // no backup recorded
  }
  return null
}

// Current state of the integration, for the Settings toggle:
//   agyFound  — agy's settings.json exists (agy CLI is installed & initialized)
//   enabled   — our hook is the active statusLine command
//   foreign   — a DIFFERENT (user's own) statusLine command is set; we won't touch it
//   mirrorAgeMs — how long since the mirror last refreshed (null = never)
export function getAgyQuotaState() {
  const cfg = readAgySettings()
  if (!cfg) return { agyFound: false, enabled: false, foreign: false, mirrorAgeMs: null }
  const cmd = (cfg.statusLine && cfg.statusLine.command) || ''
  const enabled = cmd === OUR_COMMAND
  let mirrorAgeMs = null
  try {
    mirrorAgeMs = Date.now() - fs.statSync(AGY_MIRROR_PATH).mtimeMs
  } catch {
    // mirror not written yet
  }
  const liveAge = agyQuotaAgeMs()
  if (liveAge != null) mirrorAgeMs = mirrorAgeMs == null ? liveAge : Math.min(mirrorAgeMs, liveAge)
  return { agyFound: true, enabled, foreign: !!cmd && !enabled, mirrorAgeMs }
}

// Install our hook as agy's statusLine command. Refuses (ok:false) if agy isn't
// set up, or if the user already has their own statusLine command — we never
// overwrite a foreign one.
export function enableAgyQuota() {
  const cfg = readAgySettings()
  if (!cfg) return { ok: false, reason: 'notfound' }
  const cur = (cfg.statusLine && cfg.statusLine.command) || ''
  if (cur && cur !== OUR_COMMAND) return { ok: false, reason: 'foreign' }
  writeHookFile()
  // Record the pre-existing statusLine (an object with no command can still
  // carry the user's own options, e.g. enabled:false) so disable can put it
  // back verbatim. Don't re-record once ours is already installed.
  if (cur !== OUR_COMMAND) saveStatusLineBackup(cfg)
  // Merge rather than replace, so any unrelated keys agy/the user set survive.
  cfg.statusLine = { ...(cfg.statusLine || {}), type: 'command', command: OUR_COMMAND, enabled: true }
  try {
    writeAgySettings(cfg)
  } catch {
    return { ok: false, reason: 'write' }
  }
  return { ok: true, ...getAgyQuotaState() }
}

// Remove our hook (only if it's still ours — never disturb a user's own).
export function disableAgyQuota() {
  const cfg = readAgySettings()
  if (!cfg) return { ok: true }
  const cur = (cfg.statusLine && cfg.statusLine.command) || ''
  if (cur === OUR_COMMAND) {
    const backup = readStatusLineBackup()
    if (backup && backup.had) cfg.statusLine = backup.value
    else delete cfg.statusLine // nothing there before us (or no backup) — leave agy clean
    try {
      writeAgySettings(cfg)
    } catch {
      return { ok: false, reason: 'write' }
    }
    try {
      fs.rmSync(BACKUP_PATH, { force: true })
    } catch {
      // best-effort
    }
  }
  // Drop the mirror too: it holds a stale quota snapshot, and a leftover file
  // would keep feeding agyResetWindows() after the toggle is off.
  try {
    fs.rmSync(AGY_MIRROR_PATH, { force: true })
  } catch {
    // best-effort
  }
  return { ok: true, ...getAgyQuotaState() }
}

// Re-assert the hook file on startup if the integration is enabled (the temp/
// config dir could have been cleared, or agy re-initialized). Cheap no-op
// otherwise. Never enables on its own.
export function ensureAgyHook() {
  try {
    if (getAgyQuotaState().enabled && !fs.existsSync(HOOK_PATH)) writeHookFile()
  } catch {
    // best-effort
  }
}

// Live quota windows for agy, in the shape mergeLiveLimits/toLiveWindow expect
// (same as codexResetWindows). Gemini has independent 5h and weekly buckets.
// Prefer direct fresh /usage data, then a fresh statusLine mirror.
export function agyResetWindows() {
  // The integration being off is the user saying "don't show this" — a mirror
  // left behind by an earlier session must not keep the card alive.
  try {
    if (!getAgyQuotaState().enabled) return []
  } catch {
    return []
  }
  let d
  try {
    const live = agyLiveWindows()
    if (live.length) return live
    if (Date.now() - fs.statSync(AGY_MIRROR_PATH).mtimeMs > 60000) return []
    d = JSON.parse(fs.readFileSync(AGY_MIRROR_PATH, 'utf8'))
  } catch {
    return []
  }
  return parseAgyQuota(d, fs.statSync(AGY_MIRROR_PATH).mtimeMs)
}
